/* ===================================================================
 *                    软件 I2C 底层函数
 * =================================================================== */

/* 短延迟 (~5us @ 32MHz) */
static void i2c_delay(void)
{
    delay_cycles(I2C_DELAY_CYCLES);
}

/* SCL设为高电平 (始终为输出) */
static void i2c_scl_h(void)
{
    DL_GPIO_setPins(OLED_PORT, OLED_SCL_PIN);
}

/* SCL设为低电平 */
static void i2c_scl_l(void)
{
    DL_GPIO_clearPins(OLED_PORT, OLED_SCL_PIN);
}

/*
 * SDA控制 (开漏模拟):
 *   level=1 → 释放总线, 设为输入让外部上拉电阻拉高
 *   level=0 → 设为输出并拉低总线
 */
static void i2c_sda_out(uint8_t level)
{
    if (level) {
        DL_GPIO_disableOutput(OLED_PORT, OLED_SDA_PIN);
    } else {
        DL_GPIO_clearPins(OLED_PORT, OLED_SDA_PIN);
        DL_GPIO_enableOutput(OLED_PORT, OLED_SDA_PIN);
    }
}

/* 读取SDA引脚状态, 返回0或1 */
static uint8_t i2c_sda_read(void)
{
    return (DL_GPIO_readPins(OLED_PORT, OLED_SDA_PIN) & OLED_SDA_PIN) ? 1 : 0;
}

/* I2C起始信号: SDA在SCL高电平时拉低 */
static void i2c_start(void)
{
    i2c_sda_out(1);
    i2c_delay();
    i2c_scl_h();
    i2c_delay();
    i2c_sda_out(0);
    i2c_delay();
    i2c_scl_l();
    i2c_delay();
}

/* I2C停止信号: SDA在SCL高电平时释放 */
static void i2c_stop(void)
{
    i2c_sda_out(0);
    i2c_delay();
    i2c_scl_h();
    i2c_delay();
    i2c_sda_out(1);
    i2c_delay();
}

/* I2C写一个字节, 返回从机ACK (0=ACK, 1=NACK) */
static uint8_t i2c_write_byte(uint8_t byte)
{
    uint8_t i, ack;

    for (i = 0; i < 8; i++) {
        i2c_sda_out((byte & 0x80) ? 1 : 0);
        i2c_delay();
        i2c_scl_h();
        i2c_delay();
        i2c_scl_l();
        i2c_delay();
        byte <<= 1;
    }

    /* 释放SDA, 读取从机应答 */
    i2c_sda_out(1);
    i2c_delay();
    i2c_scl_h();
    i2c_delay();
    ack = i2c_sda_read();
    i2c_scl_l();
    i2c_delay();

    return ack;
}

/* ===================================================================
 *                    SSD1306 OLED 驱动
 * =================================================================== */

/* 写命令字节 */
static void oled_write_cmd(uint8_t cmd)
{
    i2c_start();
    i2c_write_byte(OLED_I2C_ADDR << 1);    /* 写模式: 地址+W */
    i2c_write_byte(0x00);                   /* 控制字节: 命令 */
    i2c_write_byte(cmd);
    i2c_stop();
}

/* 设置页地址和列地址 (页寻址模式) */
static void oled_set_pos(uint8_t page, uint8_t col)
{
    oled_write_cmd(0xB0 | (page & 0x07));       /* 页地址 (0~7) */
    oled_write_cmd(0x00 | (col & 0x0F));         /* 列地址低4位 */
    oled_write_cmd(0x10 | ((col >> 4) & 0x0F));  /* 列地址高4位 */
}

/* ===================================================================
 *                      公开 API 实现
 * =================================================================== */

/* 清空显示缓冲区 */
void oled_clear_buf(void)
{
    memset(g_oled_buf, 0x00, sizeof(g_oled_buf));
}

/* 将缓冲区全屏刷新到OLED */
void oled_refresh(void)
{
    uint8_t page, col;
    for (page = 0; page < OLED_PAGES; page++) {
        oled_set_pos(page, 0);
        i2c_start();
        i2c_write_byte(OLED_I2C_ADDR << 1);
        i2c_write_byte(0x40);  /* 控制字节: 数据 */
        for (col = 0; col < OLED_WIDTH; col++) {
            i2c_write_byte(g_oled_buf[page][col]);
        }
        i2c_stop();
    }
}

/* 在缓冲区中绘制一个6x8字符, 返回下一字符起始列 */
uint8_t oled_draw_char(uint8_t page, uint8_t col, char c)
{
    uint8_t i;

    if (c < 0x20 || c > 0x7E) {
        c = ' ';  /* 不可打印字符替换为空格 */
    }

    if (col > OLED_WIDTH - 6) {
        return col;  /* 超出屏幕范围, 不绘制 */
    }

    for (i = 0; i < 6; i++) {
        g_oled_buf[page][col + i] = FONT_6X8[(uint8_t)(c - 0x20)][i];
    }

    /* 字符间距 (1列空白) */
    if (col + 6 < OLED_WIDTH) {
        g_oled_buf[page][col + 6] = 0x00;
    }

    return col + 7;  /* 6像素字符 + 1像素间距 */
}

/* 在缓冲区中绘制字符串 */
void oled_draw_string(uint8_t page, uint8_t col, const char *str)
{
    while (*str) {
        col = oled_draw_char(page, col, *str);
        if (col >= OLED_WIDTH - 6) break;
        str++;
    }
}

/* 反白绘制: 白底黑字 */
static uint8_t oled_draw_char_inv(uint8_t page, uint8_t col, char c) {
    if (c < 0x20 || c > 0x7E) c = ' ';
    if (col > OLED_WIDTH - 6) return col;
    for (int i = 0; i < 7 && col+i < OLED_WIDTH; i++) {
        g_oled_buf[page][col+i] = ~FONT_6X8[(uint8_t)(c-0x20)][i];
    }
    return col + 7;
}

void oled_draw_string_inv(uint8_t page, uint8_t col, const char *str) {
    int start = col;
    const char *s = str;
    while (*s) { col += 7; s++; }
    int end = col;
    if (end > OLED_WIDTH) end = OLED_WIDTH;

    /* 白底跨3页: 上页底部1px + 本页全8px + 下页顶部1px */
    if (page > 0)
        for (int x = start; x < end; x++)
            g_oled_buf[page-1][x] |= 0x80;   /* 上页最底1行变白 */
    for (int x = start; x < end; x++)
        g_oled_buf[page][x] = 0xFF;           /* 本页全白 */
    if (page < 7)
        for (int x = start; x < end; x++)
            g_oled_buf[page+1][x] |= 0x01;    /* 下页最顶1行变白 */

    /* 画黑字 */
    while (*str) {
        start = oled_draw_char_inv(page, start, *str);
        if (start >= OLED_WIDTH - 6) break;
        str++;
    }
}

/* OLED初始化 (SSD1306 128x64) */
void oled_init(void)
{
    /* 上电后等待稳定 (~10ms) */
    delay_cycles(CPUCLK_FREQ / 100);

    /* 释放I2C总线, 等待OLED上电 (~100ms) */
    DL_GPIO_setPins(OLED_PORT, OLED_SCL_PIN);
    DL_GPIO_enableOutput(OLED_PORT, OLED_SCL_PIN);
    DL_GPIO_disableOutput(OLED_PORT, OLED_SDA_PIN);
    delay_cycles(CPUCLK_FREQ / 10);

    /* SSD1306初始化命令序列 */
    oled_write_cmd(0xAE);  /* 关闭显示 */

    oled_write_cmd(0xD5);  /* 显示时钟分频/振荡器频率 */
    oled_write_cmd(0x80);  /* 默认值 */

    oled_write_cmd(0xA8);  /* 多路复用比 */
    oled_write_cmd(0x3F);  /* 64路 (128x64) */

    oled_write_cmd(0xD3);  /* 显示偏移 */
    oled_write_cmd(0x00);  /* 无偏移 */

    oled_write_cmd(0x40);  /* 显示起始行 */

    oled_write_cmd(0x8D);  /* 电荷泵设置 */
    oled_write_cmd(0x14);  /* 启用电荷泵 (3.3V供电必须) */

    oled_write_cmd(0x20);  /* 内存寻址模式 */
    oled_write_cmd(0x02);  /* 页寻址模式 */

    oled_write_cmd(0xA1);  /* 段重映射: col 127 -> SEG0 */
    oled_write_cmd(0xC8);  /* COM扫描方向: 从COM63到COM0 */

    oled_write_cmd(0xDA);  /* COM引脚硬件配置 */
    oled_write_cmd(0x12);  /* 交替COM引脚配置 */

    oled_write_cmd(0x81);  /* 对比度 */
    oled_write_cmd(0xCF);  /* 对比度值 */

    oled_write_cmd(0xD9);  /* 预充电周期 */
    oled_write_cmd(0xF1);

    oled_write_cmd(0xDB);  /* VCOMH取消选择电平 */
    oled_write_cmd(0x40);

    oled_write_cmd(0xA4);  /* 全屏显示关闭 (正常显示) */
    oled_write_cmd(0xA6);  /* 正常显示 (非反转) */

    oled_write_cmd(0x2E);  /* 停用滚动 */

    /* 清空缓冲区并刷新 */
    oled_clear_buf();
    oled_refresh();

    oled_write_cmd(0xAF);  /* 开启显示 */
}
